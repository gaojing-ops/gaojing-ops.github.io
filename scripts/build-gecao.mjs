import {readFile,writeFile,readdir} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=fileURLToPath(new URL('../games/emberfall/flux/',import.meta.url));
const sources=new Map();
async function walk(directory){for(const entry of await readdir(directory,{withFileTypes:true})){const file=path.join(directory,entry.name);if(entry.isDirectory())await walk(file);else if(entry.name.endsWith('.js'))sources.set(path.relative(root,file).replaceAll('\\','/'),await readFile(file,'utf8'));}}
await walk(path.join(root,'src'));
sources.set('entry.js',await readFile(path.join(root,'entry.js'),'utf8'));
const factories=[];
for(const [id,source] of [...sources].sort(([a],[b])=>a.localeCompare(b))){
 const dependencies={};
 for(const [,request] of source.matchAll(/\brequire\(['"]([^'"]+)['"]\)/g)){
  if(!request.startsWith('.'))throw Error(`Unexpected external dependency in ${id}: ${request}`);
  let target=path.posix.normalize(path.posix.join(path.posix.dirname(id),request));if(!target.endsWith('.js'))target+='.js';
  if(!sources.has(target))throw Error(`Missing ${target} required by ${id}`);dependencies[request]=target;
 }
 factories.push(`${JSON.stringify(id)}:[function(require,module,exports){\n${source}\n},${JSON.stringify(dependencies)}]`);
}
const bundle=`// Generated by scripts/build-gecao.mjs. Edit the source modules, then rebuild.\nimport {createBrowserPlatform,mountFlux} from './browser.mjs';\nconst browserCanvas=document.getElementById('flux-canvas');\nconst platform=createBrowserPlatform(browserCanvas);\nconst wx=platform.api,GameGlobal=globalThis;\nconst factories={${factories.join(',\n')}};\nconst cache=new Map();\nfunction load(id){if(cache.has(id))return cache.get(id).exports;const record=factories[id];if(!record)throw Error('Missing module '+id);const module={exports:{}};cache.set(id,module);record[0](request=>load(record[1][request]),module,module.exports);return module.exports;}\nconst runtime=load('entry.js');\nruntime.art=load('src/Art.js');
const catalog=(file,key)=>load('src/'+file+'.js')[key];
runtime.catalogs={
 weaponType:catalog('Weapons','Weapon'),weapons:catalog('WeaponData','weapons'),passives:catalog('WeaponData','passives'),evolution:catalog('Evolution','EVOLUTION_RECIPES'),
 skills:catalog('SkillSystem','SKILL_DEFS'),characters:catalog('Character','CHARACTERS'),
 meta:catalog('MetaSystem','META_UPGRADES'),talents:load('src/TalentTree.js'),skins:catalog('Skins','SKINS'),
 petType:catalog('Pet','Pet'),pets:catalog('Pet','PET_TYPES'),auras:catalog('Auras','AURA_TYPES'),relics:Object.fromEntries(catalog('Relic','RELIC_DEFS').map(row=>[row.id,row])),
 achievements:catalog('AchievementSystem','ACHIEVEMENT_DEFS'),builds:load('src/BuildPreset.js'),
 bosses:load('src/BossData.js'),enemies:catalog('Enemy','TYPES'),stages:catalog('StageSystem','STAGE_CONFIGS'),
 events:Object.fromEntries(catalog('EventSystem','EVENT_DEFS').map(row=>[row.id,row])),
 speed:load('src/scenes/SpeedRunScene.js'),elements:catalog('SynergySystem','ELEMENTS')
};\nawait runtime.art.preload();\nmountFlux(runtime,platform);\n`;
await writeFile(path.join(root,'bundle.mjs'),bundle);
// Version the complete ESM graph together. Import maps keep every consumer on
// one Lore/Theme instance while bypassing stale GitHub Pages/browser assets.
const modules=['browser','camp','folio','lore','theme'];
const indexPath=path.join(root,'../index.html');
let html=(await readFile(indexPath,'utf8')).replace(/<script type="importmap" id="emberfall-imports">[\s\S]*?<\/script>\s*/g,'');
const versioned=new Set(['./flux.css','flux.css','./flux/folio.css','flux/folio.css','./flux/bundle.mjs']);
html=html.replace(/(href|src)="([^"]+)"/g,(match,attribute,url)=>versioned.has(url.split('?')[0])?`${attribute}="${url.split('?')[0]}"`:match);
const hash=createHash('sha256').update(bundle).update(html);
for(const name of modules)hash.update(await readFile(path.join(root,name+'.mjs')));
hash.update(await readFile(path.join(root,'../flux.css'))).update(await readFile(path.join(root,'folio.css')));
const release=hash.digest('hex').slice(0,12);
const imports=Object.fromEntries(modules.map(name=>[`./flux/${name}.mjs`,`./flux/${name}.mjs?v=${release}`]));
html=html.replace('<script type="module" src="./flux/bundle.mjs">',`<script type="importmap" id="emberfall-imports">${JSON.stringify({imports})}</script>\n<script type="module" src="./flux/bundle.mjs">`);
html=html.replace(/(href|src)="([^"]+)"/g,(match,attribute,url)=>versioned.has(url)?`${attribute}="${url}?v=${release}"`:match);
await writeFile(indexPath,html);
console.log(`Bundled ${sources.size} CommonJS modules without changing their gameplay rules.`);
